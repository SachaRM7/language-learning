// Alias pour la compatibilité avec les noms Feather utilisés auparavant
const ALIASES = {
  'edit-3': 'pen', 'edit': 'pen', 'bar-chart-2': 'bar-chart', 'sliders': 'settings',
  'message': 'message-circle', 'map': 'route', 'type': 'languages',
};

export function icon(name, cls = '') {
  const key = P[name] ? name : (ALIASES[name] || 'help-circle');
  return `<svg class="ico ${cls}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${P[key]}</svg>`;
}

/** Remplace les anciens <i data-feather="..."> par des SVG inline. */
export function renderIcons(root = document) {
  root.querySelectorAll('i[data-feather]').forEach(el => {
    const tpl = document.createElement('template');
    tpl.innerHTML = icon(el.dataset.feather, el.getAttribute('class') || '');
    el.replaceWith(tpl.content.firstChild);
  });
}

// Shim de compatibilité : le code existant appelle feather.replace()
globalThis.feather = { replace: () => renderIcons() };
